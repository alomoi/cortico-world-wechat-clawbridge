/** 白名单的 Set 形态，供查表用。 */
export const WECHAT_BUILTIN_SET = Object.freeze(new Set(WECHAT_BUILTIN_EMOTES));

/** 是否微信真有的表情名（只看名字，不看大小写与两端空白）。 */
export function isWeChatBuiltinEmote(name) {
  const key = String(name ?? '').trim();
  if (!key) return false;
  if (WECHAT_BUILTIN_SET.has(key)) return true;
  // `ok` / `OK` / `no` / `666` 这类大小写或说法差异
  const upper = key.toUpperCase();
  return WECHAT_BUILTIN_SET.has(upper);
}
